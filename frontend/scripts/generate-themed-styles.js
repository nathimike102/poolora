/**
 * Writes src/theme/tc.ts: one Unistyles style per colour property and theme
 * colour (tc.color_text, tc.backgroundColor_surface…). Unistyles' Babel plugin
 * needs each style to read the theme explicitly, so they are written out
 * rather than built in a loop. Run after adding a colour to AppColors:
 *
 *     node scripts/generate-themed-styles.js
 */
const fs = require('fs');
const path = require('path');

const themeFile = fs.readFileSync(path.join(__dirname, '../src/theme/index.ts'), 'utf8');
const body = themeFile.match(/export interface AppColors \{([\s\S]*?)\n\}/)[1];
// cardLift is a box shadow, not a colour; cardOutline below covers it
const tokens = [...body.matchAll(/^\s+(\w+): string;/gm)].map(m => m[1]).filter(t => t !== 'cardLift');

const props = ['color', 'backgroundColor', 'borderColor', 'borderTopColor', 'borderBottomColor', 'borderLeftColor', 'borderRightColor', 'tintColor', 'shadowColor'];

const lines = [];
for (const p of props) for (const t of tokens) lines.push(`  ${p}_${t}: { ${p}: theme.colors.${t} },`);

const out = `/**
 * theme/tc.ts (generated by scripts/generate-themed-styles.js; do not edit)
 *
 * Theme colours as styles that Unistyles repaints natively when the theme
 * changes: style={[styles.card, tc.backgroundColor_surface]}.
 */

import { StyleSheet } from 'react-native-unistyles';

export const tc = StyleSheet.create(theme => ({
${lines.join('\n')}
  /** A card's thin outline and soft lift (theme/index.ts cardOutline) */
  cardOutline: { borderWidth: 1, borderColor: theme.colors.border, boxShadow: theme.colors.cardLift },
}));
`;
fs.writeFileSync(path.join(__dirname, '../src/theme/tc.ts'), out);
console.log(`tc.ts: ${lines.length + 1} styles`);
